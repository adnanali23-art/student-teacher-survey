/* استدعاء دالة في الخادم */
async function svRpc(fn, args) {
  const r = await fetch(SURVEY.supabase.url + "/rest/v1/rpc/" + fn, {
    method: "POST",
    headers: { "Content-Type": "application/json", apikey: SURVEY.supabase.key,
               Authorization: "Bearer " + SURVEY.supabase.key },
    body: JSON.stringify(args || {})
  });
  if (!r.ok) throw new Error("خطأ في الخادم (" + r.status + ")");
  return r.json();
}
function teacherLabel(id) {
  const t = TEACHERS[id];
  if (!t) return id;
  return (t.rank ? t.rank + " " : "") + t.name;
}
/* قائمة (مادة، تدريسي) لمرحلة وشعبة معيّنتين — مرتبة: السنوي ثم الفصل الأول ثم الثاني */
function assignmentsFor(dept, stage, section) {
  const s = (ASSIGNMENTS[dept] || {})[stage];
  if (!s) return [];
  return s.list
    .filter(a => !a[3] || !section || a[3].includes(section))
    .map(a => ({ subject: a[0], teacherId: a[1], sem: a[2], key: dept + "|" + stage + "|" + a[1] + "|" + a[0] }))
    .sort((x, y) => x.sem - y.sem);
}
function gradeOf(score) {
  return GRADE_BANDS.find(b => score >= b.min).t;
}
function labelValue(label) {
  const s = SCALE.find(x => x.t === String(label).trim());
  return s ? s.v : null;
}
/* المعادلة الوزارية:
   متوسط كل فقرة = مجموع (عدد التكرارات × الوزن) ÷ عدد المجيبين
   الدرجة النهائية = (متوسط متوسطات الفقرات العشر ÷ 5) × 100          */
function officialScore(rows, mode) {
  mode = mode || SURVEY.scoringMode;
  const qMeans = QUESTIONS.map((_, i) => {
    const vals = rows.map(r => r.answers[i]).filter(v => v >= 1 && v <= 5);
    const div = mode === "excel" ? vals.length + 1 : vals.length;
    return vals.length ? vals.reduce((a, b) => a + b, 0) / div : null;
  });
  const valid = qMeans.filter(m => m !== null);
  if (!valid.length) return null;
  const avg = valid.reduce((a, b) => a + b, 0) / valid.length;
  const score = (avg / 5) * 100;
  return { n: rows.length, qMeans, avg, score, grade: gradeOf(score) };
}
